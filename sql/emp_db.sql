DROP TABLE IF EXISTS `emp`;
CREATE TABLE `emp` (
    `empno` int(11) NOT NULL AUTO_INCREMENT COMMENT '员工编号',
    `ename` varchar(255) NOT NULL COMMENT '员工姓名',
    `job` varchar(255) NOT NULL COMMENT '职位',
    `mgr` int(11) NOT NULL DEFAULT 0 COMMENT '上级领导编号（0表示无上级）',
    `hiredate` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '入职日期',
    `sal` decimal(10,2) NOT NULL COMMENT '薪资',
    `comm` decimal(10,2) NOT NULL DEFAULT 0.00 COMMENT '奖金/提成',
    `deptno` int(11) NOT NULL COMMENT '部门编号',
    PRIMARY KEY (`empno`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='员工表';

